// Generate the NUU Guide product marks and favicon from the branding SVG exports.
//
//   node scripts/gen-product-icons.mjs [path-to-Logos-folder]
//
// Default source: the NUU Cognition Branding flint, Media/Logos/.
// Output: sites/guide/lib/product-icons.ts and sites/guide/app/icon.svg.
// Every mark is rewritten in currentColor so it follows the text colour in
// light and dark mode. The favicon keeps the export as is: black on white,
// the same style every NUU app uses for its tab icon.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const src =
  process.argv[2] ??
  "/Users/nathan/nuu/(Tinderbox) NUU Cognition/(Flint) NUU Cognition Branding/Media/Logos/";
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// slug in the site -> file stem in the Logos folder
const map = {
  docs: "Docs", surf: "Surf", operations: "Operations", orgs: "Organisations",
  profiles: "Profile", citations: "Citations", experience: "Experience",
  onyx: "Onyx", ncm: "ncm", mesh: "Mesh", vessel: "Vessel", guide: "Guide",
};

function inner(file) {
  let s = fs.readFileSync(path.join(src, file + ".svg"), "utf8");
  s = s.replace(/<\?xml[^>]*>/, "");
  const m = s.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error(`no <svg> in ${file}`);
  let body = m[1];
  body = body.replace(/<rect[^>]*fill="#FFFFFF"[^>]*\/>/g, "");
  body = body.replace(/<rect width="412" height="412"[^>]*\/>/g, "");
  body = body.replace(/#000000/gi, "currentColor").replace(/#FFFFFF/gi, "currentColor");
  return body.replace(/\s+/g, " ").trim();
}

let out = `import { createElement, type ReactElement } from "react";

/**
 * Product marks for NUU Guide.
 * Generated by scripts/gen-product-icons.mjs from the NUU Cognition Branding
 * flint (Media/Logos/*.svg). Do not edit by hand; rerun the script.
 * Every mark is drawn in currentColor, so it follows the text colour in
 * light and dark mode. The view box is the 412px inner bounds of the export.
 */
const marks: Record<string, string> = {
`;
for (const [slug, file] of Object.entries(map)) out += `  ${slug}: ${JSON.stringify(inner(file))},\n`;
out += `};

export type ProductSlug = keyof typeof marks;

export function hasProductIcon(slug: string | undefined): slug is ProductSlug {
  return slug !== undefined && slug in marks;
}

/** One product mark as an inline SVG element. */
export function productIcon(slug: ProductSlug, size?: number): ReactElement {
  return createElement("svg", {
    viewBox: "50 50 412 412",
    width: size,
    height: size,
    fill: "none",
    "aria-hidden": true,
    focusable: false,
    xmlns: "http://www.w3.org/2000/svg",
    dangerouslySetInnerHTML: { __html: marks[slug] },
  });
}

/** The NUU Guide mark, for the brand title. */
export function GuideLogo({ size = 18, className }: { size?: number; className?: string }) {
  return createElement("svg", {
    viewBox: "50 50 412 412",
    width: size,
    height: size,
    fill: "none",
    className,
    role: "img",
    "aria-label": "NUU Guide",
    xmlns: "http://www.w3.org/2000/svg",
    dangerouslySetInnerHTML: { __html: marks.guide },
  });
}
`;
fs.writeFileSync(path.join(repo, "sites/guide/lib/product-icons.ts"), out);
fs.copyFileSync(path.join(src, "Guide.svg"), path.join(repo, "sites/guide/app/icon.svg"));
console.log(`wrote ${Object.keys(map).length} marks and the favicon`);
